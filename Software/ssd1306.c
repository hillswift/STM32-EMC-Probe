// 写命令
void OLED_WriteCmd(uint8_t cmd)
{
    OLED_CS_Clr();
    OLED_DC_Clr();   // DC=0 发送命令
    HAL_SPI_Transmit(&hspi1, &cmd, 1, 100);
    OLED_CS_Set();
}

// 写数据
void OLED_WriteData(uint8_t data)
{
    OLED_CS_Clr();
    OLED_DC_Set();   // DC=1 发送数据
    HAL_SPI_Transmit(&hspi1, &data, 1, 100);
    OLED_CS_Set();
}

// 硬件复位
static void OLED_Reset(void)
{
    OLED_RES_Set();
    HAL_Delay(10);
    OLED_RES_Clr();  // 拉低20ms复位
    HAL_Delay(20);
    OLED_RES_Set();
    HAL_Delay(10);
}

// 屏幕初始化（96*32专用）
void OLED_Init(void)
{
    OLED_Reset();
    
    OLED_WriteCmd(0xAE); // 关闭显示
    OLED_WriteCmd(0xD5); // 时钟分频与振荡频率
    OLED_WriteCmd(0x80);
    OLED_WriteCmd(0xA8); // 设置驱动路数（32行）
    OLED_WriteCmd(0x1F);
    OLED_WriteCmd(0xD3); // 显示偏移
    OLED_WriteCmd(0x00);
    OLED_WriteCmd(0x40); // 显示起始行
    OLED_WriteCmd(0x8D); // 电荷泵设置
    OLED_WriteCmd(0x14); // 开启电荷泵
    OLED_WriteCmd(0x20); // 内存地址模式
    OLED_WriteCmd(0x02); // 页地址模式
    OLED_WriteCmd(0xA1); // 段重定义
    OLED_WriteCmd(0xC8); // COM扫描方向
    OLED_WriteCmd(0xDA); // COM硬件引脚配置
    OLED_WriteCmd(0x02); // 32行专用
    OLED_WriteCmd(0x81); // 对比度
    OLED_WriteCmd(0xCF);
    OLED_WriteCmd(0xD9); // 预充电周期
    OLED_WriteCmd(0xF1);
    OLED_WriteCmd(0xDB); // VCOMH电平
    OLED_WriteCmd(0x30);
    OLED_WriteCmd(0xA4); // 全局显示开启
    OLED_WriteCmd(0xA6); // 正常显示
    OLED_WriteCmd(0xAF); // 开启显示
    
    OLED_Clear();
}

// 清屏
void OLED_Clear(void)
{
    for(uint8_t i = 0; i < OLED_HEIGHT/8; i++)
    {
        OLED_WriteCmd(0xB0 + i);    // 设置页地址
        OLED_WriteCmd(0x00);        // 列地址低4位
        OLED_WriteCmd(0x10);        // 列地址高4位
        for(uint8_t j = 0; j < OLED_WIDTH; j++)
        {
            OLED_WriteData(0x00);
        }
    }
}

// 显示单个字符（6x8字号）
void OLED_ShowChar(uint8_t x, uint8_t y, uint8_t chr, uint8_t size)
{
    uint8_t c = chr - ' '; // 字符偏移
    
    if(x > OLED_WIDTH - 1) {x = 0; y++;}
    if(size == 12) // 6x8字体
    {
        OLED_WriteCmd(0xB0 + y);
        OLED_WriteCmd(((x&0xF0)>>4)|0x10);
        OLED_WriteCmd((x&0x0F)|0x00);
        for(uint8_t i=0;i<6;i++)
            OLED_WriteData(F6x8[c][i]);
    }
}

// 显示字符串
void OLED_ShowString(uint8_t x, uint8_t y, uint8_t *str, uint8_t size)
{
    while(*str)
    {
        OLED_ShowChar(x, y, *str, size);
        x += 6;
        str++;
    }
}

// 显示浮点数（保留1位小数，len为整数部分位数）
void OLED_ShowNum(uint8_t x, uint8_t y, float num, uint8_t len, uint8_t size)
{
    uint8_t int_part = (uint8_t)num;
    uint8_t dec_part = (uint8_t)((num - int_part)*10);
    
    // 显示整数部分
    for(uint8_t i=0; i<len; i++)
    {
        OLED_ShowChar(x + 6*(len-1-i), y, '0' + (int_part%10), size);
        int_part /= 10;
    }
    // 显示小数点
    OLED_ShowChar(x + 6*len, y, '.', size);
    // 显示小数部分
    OLED_ShowChar(x + 6*(len+1), y, '0' + dec_part, size);
}
